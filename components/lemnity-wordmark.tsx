/**
 * Цвет вспышки каждой буквы — из палитры волны правой половины
 * ([login-shape-wave.tsx](./login-shape-wave.tsx) `PALETTE`). Совпадение не
 * случайное: букв семь и «чистых» цветов волны берём семь, поэтому подпись
 * подхватывает ровно те оттенки, что летают справа, и половины экрана читаются
 * как одна сцена, а не как логотип рядом с посторонней заставкой.
 *
 * Индекс — позиция СЛЕВА НАПРАВО (`order`), не индекс в DOM.
 */
/**
 * Цвета волны. Экспортируются: этой же палитрой красятся символы при наборе текста
 * на лендинге (`typed-glitch`), и держать там копию нельзя — разъедется со знаком.
 */
export const LETTER_COLORS = [
  "#22c55e",
  "#06b6d4",
  "#f97316",
  "#ef4444",
  "#facc15",
  "#ec4899",
  "#a78bfa",
];

/** Спокойный ритм: волна пробегает подпись и знак «отдыхает» до следующего круга.
 *  Пауза обязательна — без неё непрерывное движение на форме входа отвлекает от
 *  заполнения полей. */
const IDLE = { cycleMs: 2600, staggerMs: 90 };
/** Пока уходит запрос авторизации: круг короче и волна плотнее — движение
 *  превращается в индикатор «идёт обработка» (UX-правило: показывать прогресс
 *  для операций дольше 300 мс), а не в украшение. */
const BUSY = { cycleMs: 1000, staggerMs: 45 };

/**
 * Стили держим локально в `<style>`, а не в `app/globals.css` / `tailwind.config.ts`:
 * это единственное место, где нужны эти кейфреймы, а оба общих файла правятся
 * параллельно другими задачами.
 *
 * Вся анимация обёрнута в `@media (prefers-reduced-motion: no-preference)` —
 * при включённом «уменьшить движение» правила просто не объявляются, и знак
 * остаётся статичным (это критическое требование доступности, а не опция).
 */
const WORDMARK_STYLES = `
@media (prefers-reduced-motion: no-preference) {
  .lmnt-wm-letter {
    /* fill-box — чтобы масштаб шёл от центра САМОЙ буквы, иначе точкой отсчёта
       стал бы левый верхний угол всего viewBox и буквы разъезжались бы. */
    transform-box: fill-box;
    transform-origin: center;
    animation: lmnt-wm-hop var(--lmnt-wm-cycle) cubic-bezier(0.34, 1.56, 0.64, 1) var(--lmnt-wm-delay) infinite both;
  }
  .lmnt-wm:hover .lmnt-wm-letter {
    animation-name: lmnt-wm-hop-strong;
  }
}

/* Активная фаза — первые ~18% круга, остальное покой. Двигаем только transform
   и fill: раскладка не пересчитывается, сдвига макета не возникает. */
@keyframes lmnt-wm-hop {
  0%   { transform: translateY(0) scale(1);       fill: currentColor; }
  5%   { transform: translateY(-3px) scale(1.13); fill: var(--lmnt-wm-color); }
  11%  { transform: translateY(0) scale(0.96);    fill: var(--lmnt-wm-color); }
  18%  { transform: translateY(0) scale(1);       fill: currentColor; }
  100% { transform: translateY(0) scale(1);       fill: currentColor; }
}

/* По наведению та же волна, но заметнее — реакция на курсор без смены ритма. */
@keyframes lmnt-wm-hop-strong {
  0%   { transform: translateY(0) scale(1);       fill: currentColor; }
  5%   { transform: translateY(-5px) scale(1.22); fill: var(--lmnt-wm-color); }
  11%  { transform: translateY(0) scale(0.94);    fill: var(--lmnt-wm-color); }
  18%  { transform: translateY(0) scale(1);       fill: currentColor; }
  100% { transform: translateY(0) scale(1);       fill: currentColor; }
}
`;

export function LemnityWordmark({
  className,
  animated = false,
  busy = false,
}: {
  className?: string;
  /** Зациклённая волна по буквам, пока компонент смонтирован — то есть всё
   *  время, пока человек входит или регистрируется. */
  animated?: boolean;
  /** Идёт запрос авторизации: волна ускоряется и уплотняется. */
  busy?: boolean;
}) {
  const tempo = busy ? BUSY : IDLE;

  return (
    <>
      {/* `href` + `precedence` — штатный подъём стилей в `<head>` у React 19.
          Без них тег остался бы внутри `<a>` (браузеры это терпят, но это
          невалидная вложенность), а при повторном рендере знака правила
          продублировались бы; с ними React вставляет их один раз. */}
      {animated ? (
        <style href="lemnity-wordmark" precedence="default">
          {WORDMARK_STYLES}
        </style>
      ) : null}
      <svg
        viewBox="0 0 169 38"
        fill="currentColor"
        xmlns="http://www.w3.org/2000/svg"
        role="img"
        aria-label="Lemnity"
        className={cn("lmnt-wm block shrink-0", className)}
        style={
          animated
            ? ({
                "--lmnt-wm-cycle": `${tempo.cycleMs}ms`,
              } as React.CSSProperties)
            : undefined
        }
      >
        {LETTERS.map((letter) => (
          <path
            key={letter.order}
            d={letter.d}
            className={animated ? "lmnt-wm-letter" : undefined}
            style={
              animated
                ? ({
                    "--lmnt-wm-delay": `${letter.order * tempo.staggerMs}ms`,
                    "--lmnt-wm-color": LETTER_COLORS[letter.order],
                  } as React.CSSProperties)
                : undefined
            }
          />
        ))}
      </svg>
    </>
  );
}
